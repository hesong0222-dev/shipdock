// Render Homebrew, Scoop and winget manifests from a plan's picks plus inspect() results.
// meta: { owner, repo, name, desc, homepage, license, version }
// info: { [asset name]: { sha256, root, bin } }

export const HEADER = 'generated by shipdock; review before submitting';

const cleanDesc = (d) => (d || '').replace(/:[a-z0-9_+-]+:/g, '').replace(/\s+/g, ' ').trim();

// Homebrew audit rules: no leading article, no formula name, no trailing period, under 80 chars
// (cut at the last clause boundary, else word boundary).
export function brewDesc(desc, name) {
  let d = cleanDesc(desc).replace(/\.$/, '').replace(/^(a|an|the)\s+/i, '');
  if (d.toLowerCase().startsWith(name.toLowerCase() + ' ')) d = d.slice(name.length + 1);
  d = d.charAt(0).toUpperCase() + d.slice(1);
  if (d.length < 80) return { desc: d, shortened: false };
  const head = d.slice(0, 80);
  const cut = head.match(/^(.*\S)(?:,| while| that| which| with| -| —|;)\s/) || head.match(/^(.*\S)\s/);
  return { desc: cut ? cut[1] : head.slice(0, 79), shortened: true };
}

// Homebrew's Formulary.class_s
export const className = (name) => name.replace(/^./, (c) => c.toUpperCase()).replace(/[-_.\s]([a-zA-Z0-9])/g, (_, c) => c.toUpperCase()).replace(/\+/g, 'x');

function used(mgr, info) {
  const out = {};
  for (const [slot, a] of Object.entries(mgr.picks)) if (a && info[a.name] && info[a.name].sha256) out[slot] = { a, i: info[a.name] };
  return out;
}

// One executable path for all archives, or a fallback plus a TODO line explaining why.
function chooseBin(paths, fallback) {
  const found = [...new Set(paths.filter(Boolean))];
  if (found.length === 1 && paths.every(Boolean)) return { bin: found[0], todo: null };
  if (!found.length) return { bin: fallback, todo: `TODO: no executable found inside the archive(s); assumed "${fallback}". Check the archive layout.` };
  return { bin: found[0], todo: `TODO: executable path differs between archives (${found.join(', ')}); using "${found[0]}".` };
}

export function renderFormula(meta, mgr, info) {
  const u = used(mgr, info);
  const { bin, todo } = chooseBin(Object.values(u).map((x) => x.i.bin), meta.name);
  const src = (x, ind) => [`${ind}url "${x.a.url}"`, `${ind}sha256 "${x.i.sha256}"`];
  const d = brewDesc(meta.desc, meta.name);
  const L = [`# ${HEADER}`];
  if (todo) L.push(`# ${todo}`);
  if (d.shortened) L.push('# TODO: description was shortened to fit Homebrew\'s 80-character limit; reword it.');
  L.push(`class ${className(meta.name)} < Formula`, `  desc "${d.desc.replace(/"/g, '\\"')}"`, `  homepage "${meta.homepage}"`);
  // brew audit --strict rejects a `version` it can already read from the URLs.
  if (!Object.values(u).every((x) => x.a.name.includes(meta.version))) L.push(`  version "${meta.version}"`);
  if (meta.license) L.push(`  license "${meta.license}"`);
  for (const [os, block] of [['darwin', 'on_macos'], ['linux', 'on_linux']]) {
    const arm = u[`${os}-arm64`], intel = u[`${os}-amd64`];
    if (!arm && !intel) continue;
    L.push('', `  ${block} do`);
    if (arm && intel && arm.a === intel.a) L.push(...src(arm, '    '));
    else {
      if (arm) L.push('    if Hardware::CPU.arm?', ...src(arm, '      '), '    end');
      if (intel) L.push('    if Hardware::CPU.intel?', ...src(intel, '      '), '    end');
    }
    L.push('  end');
  }
  L.push('', '  def install', `    bin.install "${bin}"`, '  end', '', '  test do', `    system bin/"${bin.split('/').pop()}", "--version"`, '  end', 'end', '');
  return L.join('\n');
}

const winBin = (x, name) => (x.a.format === 'exe' ? `${name}.exe` : x.i.bin);

export function renderScoop(meta, mgr, info) {
  const u = used(mgr, info);
  const { bin, todo } = chooseBin(Object.values(u).map((x) => winBin(x, meta.name)), `${meta.name}.exe`);
  const arch = {}, auto = {};
  for (const [slot, key] of [['windows-amd64', '64bit'], ['windows-arm64', 'arm64']]) {
    const x = u[slot];
    if (!x) continue;
    const frag = x.a.format === 'exe' ? `#/${meta.name}.exe` : '';
    const tmpl = (s) => s.split(meta.version).join('$version');
    arch[key] = { url: x.a.url + frag, hash: x.i.sha256 };
    auto[key] = { url: tmpl(x.a.url) + frag };
    if (x.i.root) { arch[key].extract_dir = x.i.root; auto[key].extract_dir = tmpl(x.i.root); }
  }
  const m = { '##': todo ? [HEADER, todo] : HEADER, version: meta.version, description: cleanDesc(meta.desc) || meta.name, homepage: meta.homepage };
  if (meta.license) m.license = meta.license;
  Object.assign(m, { architecture: arch, bin, checkver: 'github', autoupdate: { architecture: auto } });
  return JSON.stringify(m, null, 4) + '\n';
}

const q = (s) => (/^[A-Za-z_][\w.\-/\\]*$/.test(s) ? s : JSON.stringify(s));

// The singleton schema allows exactly one installer; pickFor() already kept only one.
export function renderWinget(meta, mgr, info) {
  const u = used(mgr, info);
  const [slot, archName] = [['windows-amd64', 'x64'], ['windows-arm64', 'arm64']].find(([k]) => u[k]);
  const x = u[slot];
  const type = x.a.format === 'exe' ? 'portable' : x.a.format;
  const L = [`# ${HEADER}`];
  if (type === 'zip' && !x.i.bin) L.push(`# TODO: no executable found inside the archive; assumed "${meta.name}.exe". Check the archive layout.`);
  L.push(
    '# yaml-language-server: $schema=https://aka.ms/winget-manifest.singleton.1.6.0.schema.json',
    `PackageIdentifier: ${q(`${meta.owner}.${meta.repo}`)}`, `PackageVersion: ${q(meta.version)}`, 'PackageLocale: en-US',
    `Publisher: ${q(meta.owner)}`, `PackageName: ${q(meta.repo)}`, `PackageUrl: ${q(meta.homepage)}`,
    `License: ${q(meta.license || meta.licenseName || 'Unknown')}`, `ShortDescription: ${q(cleanDesc(meta.desc).slice(0, 256) || meta.repo)}`,
    'Installers:',
    `- Architecture: ${archName}`, `  InstallerType: ${type}`, `  InstallerUrl: ${q(x.a.url)}`, `  InstallerSha256: ${x.i.sha256.toUpperCase()}`,
  );
  if (type === 'zip') {
    const bin = x.i.bin || `${meta.name}.exe`;
    L.push('  NestedInstallerType: portable', '  NestedInstallerFiles:',
      `  - RelativeFilePath: ${q([x.i.root, bin].filter(Boolean).join('/').replace(/\//g, '\\'))}`,
      `    PortableCommandAlias: ${q(bin.split('/').pop().replace(/\.exe$/i, ''))}`);
  }
  if (type === 'portable') L.push('  Commands:', `  - ${q(meta.name)}`);
  L.push('ManifestType: singleton', 'ManifestVersion: 1.6.0', '');
  return L.join('\n');
}
