import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { plan } from '../src/classify.mjs';
import { renderFormula, renderScoop, renderWinget, brewDesc, className, perPlatform } from '../src/render.mjs';

const release = JSON.parse(readFileSync(new URL('./fixtures/release.json', import.meta.url), 'utf8'));
const p = plan('acme/tool', release);
const meta = { owner: 'acme', repo: 'tool', name: 'tool', desc: 'A tiny tool.', homepage: 'https://github.com/acme/tool', license: 'MIT', version: '1.2.0' };

// What inspect() would return for each picked asset: hash from the digest, binary under a top-level dir.
function infoFor(bin = (a) => (a.os === 'windows' ? 'tool.exe' : 'tool')) {
  const info = {};
  for (const a of p.assets) info[a.name] = { sha256: a.digest.slice(7), root: a.name.replace(/\.(tar\.gz|zip)$/, ''), bin: bin(a) };
  return info;
}
const sha = (name) => p.assets.find((a) => a.name === name).digest.slice(7);

test('Homebrew formula: header, arch blocks, url+sha256, bin.install', () => {
  const rb = renderFormula(meta, p.managers.homebrew, infoFor());
  assert.match(rb, /^# generated by shipdock; review before submitting\nclass Tool < Formula\n/);
  assert.match(rb, /desc "Tiny tool"/);
  assert.match(rb, /on_macos do\n    if Hardware::CPU\.arm\?\n      url "[^"]+aarch64-apple-darwin\.tar\.gz"\n      sha256 "[0-9a-f]{64}"\n    end\n    if Hardware::CPU\.intel\?/);
  assert.match(rb, /on_linux do\n    if Hardware::CPU\.intel\?\n      url "[^"]+x86_64-unknown-linux-gnu\.tar\.gz"/);
  assert.doesNotMatch(rb, /on_linux do\n    if Hardware::CPU\.arm\?/);
  assert.ok(rb.includes(`sha256 "${sha('tool-v1.2.0-x86_64-apple-darwin.tar.gz')}"`));
  assert.match(rb, /def install\n    bin\.install "tool"\n  end/);
  assert.doesNotMatch(rb, /^\s*version "/m, 'version is redundant when the URLs carry it');
  assert.doesNotMatch(rb, /TODO/);
});

test('Homebrew formula: universal mac asset goes straight into on_macos', () => {
  const u = plan('acme/tool', { tag_name: 'v1.0.0', assets: [{ name: 'tool-1.0.0-macos-universal.tar.gz', size: 1, digest: `sha256:${'a'.repeat(64)}`, browser_download_url: 'https://x/tool-1.0.0-macos-universal.tar.gz' }] });
  const rb = renderFormula({ ...meta, version: '1.0.0' }, u.managers.homebrew, { 'tool-1.0.0-macos-universal.tar.gz': { sha256: 'a'.repeat(64), root: '', bin: 'tool' } });
  assert.match(rb, /on_macos do\n    url "https:\/\/x\/tool-1\.0\.0-macos-universal\.tar\.gz"\n    sha256 "a{64}"\n  end/);
  assert.doesNotMatch(rb, /Hardware::CPU|on_linux/);
});

test('missing executable falls back to the repo name with a TODO header', () => {
  const rb = renderFormula(meta, p.managers.homebrew, infoFor(() => null));
  assert.match(rb, /^# generated by shipdock; review before submitting\n# TODO: no executable found/);
  assert.match(rb, /bin\.install "tool"/);
  const scoop = JSON.parse(renderScoop(meta, p.managers.scoop, infoFor(() => null)));
  assert.match(scoop['##'][1], /^TODO: no executable found/);
  assert.match(renderWinget(meta, p.managers.winget, infoFor(() => null)), /\n# TODO: no executable found/);
});

test('Scoop manifest: architecture, hash, extract_dir, bin, checkver, autoupdate', () => {
  const m = JSON.parse(renderScoop(meta, p.managers.scoop, infoFor()));
  assert.equal(m['##'], 'generated by shipdock; review before submitting');
  assert.equal(m.version, '1.2.0');
  assert.deepEqual(Object.keys(m.architecture), ['64bit']);
  assert.equal(m.architecture['64bit'].hash, sha('tool-v1.2.0-x86_64-pc-windows-msvc.zip'));
  assert.equal(m.architecture['64bit'].extract_dir, 'tool-v1.2.0-x86_64-pc-windows-msvc');
  assert.equal(m.bin, 'tool.exe');
  assert.equal(m.checkver, 'github');
  assert.equal(m.autoupdate.architecture['64bit'].url, 'https://github.com/acme/tool/releases/download/v$version/tool-v$version-x86_64-pc-windows-msvc.zip');
  assert.equal(m.autoupdate.architecture['64bit'].extract_dir, 'tool-v$version-x86_64-pc-windows-msvc');
});

test('winget singleton: one zip installer with a nested portable exe', () => {
  const y = renderWinget(meta, p.managers.winget, infoFor());
  assert.match(y, /^# generated by shipdock; review before submitting\n/);
  assert.match(y, /\nPackageIdentifier: acme\.tool\nPackageVersion: "1\.2\.0"\n/);
  assert.equal((y.match(/- Architecture:/g) || []).length, 1);
  assert.match(y, /- Architecture: x64\n  InstallerType: zip\n  InstallerUrl: "[^"]+msvc\.zip"\n  InstallerSha256: [0-9A-F]{64}\n  NestedInstallerType: portable\n  NestedInstallerFiles:\n  - RelativeFilePath: tool-v1\.2\.0-x86_64-pc-windows-msvc\\tool\.exe\n    PortableCommandAlias: tool\n/);
  assert.match(y, /ManifestType: singleton\nManifestVersion: 1\.6\.0\n$/);
});

test('brew desc follows audit rules', () => {
  assert.deepEqual(brewDesc(':rocket: The fast thing.', 'x'), { desc: 'Fast thing', shortened: false });
  assert.equal(brewDesc('ripgrep searches files', 'ripgrep').desc, 'Searches files');
  const long = brewDesc('ripgrep recursively searches directories for a regex pattern while respecting your gitignore', 'ripgrep');
  assert.deepEqual(long, { desc: 'Recursively searches directories for a regex pattern', shortened: true });
  assert.equal(className('git-lfs'), 'GitLfs');
});

test('per-platform executable names: one install line per platform, renamed to the shared name', () => {
  assert.equal(perPlatform(['zigscient-aarch64-macos', 'zigscient-x86_64-linux']), 'zigscient');
  assert.equal(perPlatform(['browserpass-darwin-arm64', 'browserpass-linux64']), 'browserpass');
  assert.equal(perPlatform(['xreferee-1.1.1-osx-arm64', 'xreferee-1.1.1-linux-x86_64']), 'xreferee');
  assert.equal(perPlatform(['tool', 'tool']), null);
  const assets = ['aarch64-macos', 'x86_64-macos', 'x86_64-linux'].map((s) => ({ name: `zs-${s}.zip`, size: 1, digest: `sha256:${'b'.repeat(64)}`, browser_download_url: `https://github.com/a/zs/releases/download/0.17.0/zs-${s}.zip` }));
  const q = plan('a/zs', { tag_name: '0.17.0', assets });
  const info = Object.fromEntries(assets.map((a) => [a.name, { sha256: 'b'.repeat(64), root: '', bin: a.name.replace('.zip', ''), chmod: a.name.includes('macos') }]));
  const rb = renderFormula({ ...meta, name: 'zs', version: '0.17.0' }, q.managers.homebrew, info);
  assert.match(rb, /    if OS\.mac\?\n      if Hardware::CPU\.arm\?\n        chmod 0755, "zs-aarch64-macos"\n        bin\.install "zs-aarch64-macos" => "zs"\n      end/);
  assert.match(rb, /    if OS\.linux\? && Hardware::CPU\.intel\?\n      bin\.install "zs-x86_64-linux" => "zs"\n    end/);
  assert.match(rb, /system bin\/"zs", "--version"/);
  assert.doesNotMatch(rb, /TODO|^\s*version "/m, 'the /releases/download/0.17.0/ path already carries the version');
});

test('brew desc drops a leading formula name the way brew audit matches it', () => {
  assert.deepEqual(brewDesc('Browserpass native client app', 'browserpass-native'), { desc: 'Client app', shortened: true });
});
